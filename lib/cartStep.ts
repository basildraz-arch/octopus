import type { Item } from "@/types/item";

// خطوة الزيادة والنقصان في السلة.
//
// ============================================================
// ليه الخطوة مش واحدة لكل الأصناف
// ============================================================
//
// كيرو طلب أزرار + و− عشان يزوّد وينقّص من غير ما يفتح نافذة ويكتب
// رقم. بس "واحد" معناها حاجة مختلفة حسب الصنف:
//
//   كوباية شاي   → +١ يعني كوباية زيادة        ✅
//   بن بالكيلو   → +١ يعني **كيلو زيادة**      ❌ محدش بيعمل كده
//
// المصري بيشتري البن **بالربع كيلو**. فخطوة الوزن ربع، والقطعة حبة.
//
// ============================================================
// وليه الأصناف اللي بتتباع بالمبلغ مالهاش أزرار
// ============================================================
//
// `sale_method = 'money'` معناها الزبون بيقول "هات بعشرين جنيه"،
// والكمية بتتحسب من المبلغ (`المبلغ ÷ سعر الوحدة`). فزرار + هيزوّد
// **كمية** والمبلغ هيقفز بسعر وحدة كامل - يعني ٢٠ ج تبقى ٤٥ ج
// بدوسة. ده مش "زوّد براحتك"، ده مفاجأة.
//
// الأصناف دي بتتعدّل من النافذة اللي بتكتب فيها المبلغ، وde الصح.

const STEPS: Record<Item["sale_method"], number | null> = {
  piece: 1,
  weight: 0.25,
  money: null,
};

/** خطوة الصنف، أو `null` لو مالهوش أزرار + و−. */
export function stepFor(item: Item): number | null {
  return STEPS[item.sale_method] ?? null;
}

// الكميات في القاعدة `numeric(14,4)`. الجمع المتكرر في جافاسكريبت
// بيطلّع 0.30000000000000004، ولو اتبعت زي ما هو الرقم اللي بيتخزّن
// بيتقرّب وبيفرق عن اللي على الشاشة.
//
// بنقرّب لأربع خانات - **نفس دقة العمود بالظبط**، لا أكتر ولا أقل.
export function roundQuantity(value: number): number {
  return Math.round(value * 10_000) / 10_000;
}

/**
 * الكمية الجديدة بعد دوسة على + أو −.
 *
 * بترجّع `null` لو الدوسة مالهاش معنى (صنف بالمبلغ، أو نقصان
 * هيوصّل لصفر أو أقل). **النقصان مابيمسحش السطر** - المسح ليه زرار
 * لوحده، وحاجة بتمسح بدوسة على "−" بتحصل بالغلط.
 */
export function nextQuantity(
  item: Item,
  current: number,
  direction: 1 | -1
): number | null {
  const step = stepFor(item);

  if (step === null) return null;

  const next = roundQuantity(current + step * direction);

  if (next <= 0) return null;

  return next;
}
