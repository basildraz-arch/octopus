// عمر الوردية المفتوحة.
//
// ============================================================
// المشكلة اللي الملف ده اتعمل عشانها
// ============================================================
//
// `getOrCreateOpenShift` بترجّع الوردية المفتوحة لو لقتها، ومابتسألش
// هي مفتوحة من إمتى. ومفيش حاجة في البرنامج بتقفل اليوم لوحدها ولا
// بتنبّه.
//
// النتيجة على محل حقيقي (قاف، أسوان):
//
//     وردية ٢٧ أغسطس   →  ١٠ ساعات   ✅
//     وردية ٢٨ ← ٣١    →  ٧٤ ساعة    ← تلات أيام في وردية واحدة
//     الوردية الحالية   →  ٢٥ ساعة    ← ولسه مفتوحة
//
// وده بيكسّر تلات حاجات مع بعض:
//
// ١. **جرد الدرج بقى بلا معنى.** "الكاش المتوقع" بيتحسب من أول
//    الوردية. تلات أيام مبيعات ومصروفات في رقم واحد، وصاحب المحل
//    بيعدّ الدرج ويلاقي فرق مايعرفش جه منين.
//
// ٢. **كل شاشة مربوطة بالوردية بتوري تلات أيام كأنهم النهاردة.**
//    ده بالظبط اللي كيرو وصفه بـ"بيسجل فواتير قديمة كتير".
//
// ٣. **التقارير اليومية مالهاش يوم.** الوردية هي اليوم في البرنامج،
//    فلو الوردية تلات أيام، اليوم بقى تلات أيام.
//
// الملف ده بيجاوب على سؤال واحد: الوردية دي عدّت يومها؟ والشاشة
// بتقرر تعمل إيه بالإجابة.
//
// **ليه ملف نقي لوحده:** نفس السؤال بيتسأل في شاشة الكاشير وفي
// الرئيسية وفي قفل اليوم. لو الحساب اتكرر في التلاتة هيفرقوا مع
// الوقت — نفس النمط المتّبع في `lib/pinRules.ts` و`lib/referralRules.ts`.

// كام ساعة تعتبر الوردية "طويلة أوي".
//
// **مش ٢٤.** الكافيه بيفتح ٩ الصبح ويقفل ٢ بالليل = ١٧ ساعة، وde
// يوم عادي مش مشكلة. ١٨ بتسيب مساحة ليوم طويل من غير ما تنبّه غلط.
const LONG_HOURS = 18;

export type ShiftAge = {
  hours: number;
  // فتحت في يوم تقويمي فات؟ ده أهم من عدد الساعات: وردية فتحت
  // امبارح الساعة ١١ بالليل ولسه مفتوحة الصبح = يومين على الورق حتى
  // لو ٩ ساعات بس.
  crossedMidnight: boolean;
  tooLong: boolean;
  // نص جاهز للعرض. بيتحط هنا مش في الكومبوننت عشان الشاشات التلاتة
  // يقولوا نفس الكلام.
  label: string;
};

function hoursBetween(from: Date, to: Date): number {
  return (to.getTime() - from.getTime()) / 3_600_000;
}

function sameCalendarDay(a: Date, b: Date): boolean {
  return (
    a.getFullYear() === b.getFullYear() &&
    a.getMonth() === b.getMonth() &&
    a.getDate() === b.getDate()
  );
}

export function shiftAge(openedAt: string, now: Date = new Date()): ShiftAge {
  const opened = new Date(openedAt);

  const hours = Math.max(0, hoursBetween(opened, now));
  const crossedMidnight = !sameCalendarDay(opened, now);
  const tooLong = crossedMidnight || hours >= LONG_HOURS;

  const days = Math.floor(hours / 24);

  const label =
    days >= 1
      ? `الوردية مفتوحة من ${days === 1 ? "يوم" : `${days} أيام`}`
      : `الوردية مفتوحة من ${Math.floor(hours)} ساعة`;

  return { hours, crossedMidnight, tooLong, label };
}
