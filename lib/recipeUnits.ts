// ============================================================
// وحدات الوصفة — الجرام والمل
// ============================================================
//
// المشكلة اللي الملف ده موجود عشانها:
//
// البن بيتشترى **بالكيلو**، والكوباية بتاخد **١٨ جرام**. الوصفة
// بتتخزّن في القاعدة بوحدة المكوّن نفسه، يعني `0.018`.
//
// وde كان اللي بيوقّف الوصفة خالص. صاحب محل مابيقعدش يحوّل ١٨ جرام
// لـ٠.٠١٨ في دماغه، لا لكوباية ولا لخمسة وأربعين مشروب × تلات
// مكوّنات. وأول غلطة في مكان العلامة العشرية (٠.١٨ بدل ٠.٠١٨)
// بتخلّي الكيلو يخلص في خمس كوبايات، وساعتها البرنامج يرفض البيع
// وهو محق حسابيًا وغلط في نظر اللي واقف على الكاشير.
//
// فالحل إنه يكتب **١٨** ويختار **جرام**، والبرنامج يقسم على ١٠٠٠.
//
// ليه ملف لوحده ومحدش بيخزّن الوحدة دي في القاعدة:
// الوحدة الصغيرة **مشتقّة** من وحدة المكوّن، مش معلومة جديدة.
// الكيلو جراماته ألف في كل محل في الدنيا. تخزينها كان معناه عمود
// زيادة وميجريشن وحالة "الوحدة المخزّنة مش متسقة مع وحدة الصنف"
// لازم حد يتعامل معاها - مقابل صفر معلومة مكسوبة.
//
// والملف **خالص**: نفس الدخل = نفس الخرج، فبيتجرّب من غير متصفح
// ولا قاعدة بيانات.

export type SubUnit = {
  /** الاسم اللي بيظهر لصاحب المحل: "جرام" أو "مل" */
  name: string;

  /** كام وحدة صغيرة في الوحدة الكبيرة */
  per: number;
};

// الأسماء اللي الناس بتكتبها فعلًا. الليستة مقصود إنها **ضيقة**:
// لو وحدة مش هنا، بنسيب الإدخال بوحدة المكوّن زي ما هي - وde
// أأمن من إننا نخمّن ونقسم على ألف بالغلط.
const KILO = /^(كيلو|كيلة|كجم|كغم|كيلوجرام|كيلوغرام|kg|kilo|kilogram|kilogramme)$/i;

const LITER = /^(لتر|لترة|لتره|ليتر|ل\.?|l|lt|liter|litre|ltr)$/i;

/**
 * الوحدة الصغيرة المناسبة لوحدة المكوّن، أو `null` لو مافيش.
 *
 * كيلو → جرام، لتر → مل. أي حاجة تانية (قطعة، كوب، زجاجة) مالهاش
 * وحدة أصغر منطقية فبتتكتب بوحدتها.
 */
export function subUnitFor(unit: string | null | undefined): SubUnit | null {
  const clean = (unit ?? "").trim();

  if (KILO.test(clean)) return { name: "جرام", per: 1000 };
  if (LITER.test(clean)) return { name: "مل", per: 1000 };

  return null;
}

/** بيشيل الأصفار الزايدة: 18.000000000000004 → 18، 0.0180 → 0.018 */
function tidy(value: number): number {
  return Number(value.toFixed(4));
}

/**
 * الرقم اللي بيتخزّن في القاعدة.
 *
 * `inSubUnit` معناها إن اللي مكتوب في الخانة بالوحدة الصغيرة
 * (١٨ جرام)، فبنقسم. لو `false` فهو بوحدة المكوّن أصلًا.
 */
export function toStoredQuantity(
  typed: number,
  unit: string | null | undefined,
  inSubUnit: boolean
): number {
  if (!inSubUnit) return tidy(typed);

  const sub = subUnitFor(unit);

  if (!sub) return tidy(typed);

  return tidy(typed / sub.per);
}

/**
 * الرقم المخزّن مكتوب بشكل بني آدم.
 *
 * `0.018` مع وحدة `كيلو` بترجع `"18 جرام"` - مش `"0.018 كيلو"`.
 * بنحوّل بس لما الرقم **أصغر من واحد**، عشان `2.5 كيلو` تفضل
 * كيلو ومابتتحوّلش لـ`2500 جرام`.
 */
export function describeQuantity(
  stored: number,
  unit: string | null | undefined
): string {
  const sub = subUnitFor(unit);

  if (sub && stored > 0 && stored < 1) {
    return `${tidy(stored * sub.per)} ${sub.name}`;
  }

  return `${tidy(stored)} ${(unit ?? "").trim()}`.trim();
}
