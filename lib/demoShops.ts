// ============================================================
// اسطمبات العرض — الأداة اللي المسوّق بيبيع بيها
// ============================================================
//
// باسل: "كل مسوق ليه أكونت محدود تسويقي وعنده اسطمبات ثابتة لكل نوع
// نشاط يقدر يفرجه ليه."
//
// المسوّق واقف قدام صاحب صيدلية. أسوأ حاجة يعملها إنه يفتحله شاشة
// فيها "لاتيه" و"كابتشينو" ويقوله "تخيّل إن دي أدوية". أول ثانية
// من العرض بتحدد باقي الكلام.
//
// ------------------------------------------------------------
// ليه ده ملف بيانات، مش حسابات حقيقية في القاعدة
// ------------------------------------------------------------
//
// الحل الواضح كان: نعمل ١٠ محلات تجريبية في القاعدة والمسوّق يدخلها
// بحساب. وde كان هيجيب أربع مشاكل:
//
//   ١. محلات حقيقية في `businesses` بتظهر في كل إحصائية وتقرير
//      عند باسل، وبتخلط العدد الحقيقي بالوهمي.
//   ٢. المسوّق بيبيع فيها ويمسح ويلخبط، والمحل التاني اللي هيتعرض
//      عليه بكرة بيلاقي الشاشة مليانة زبالة.
//   ٣. المسوّق بيبقى معاه دخول لحساب حقيقي - يعني RLS بتشوفه
//      كمستخدم في محل، وde بيفتح باب كنا قافلينه.
//   ٤. النت لازم يكون شغّال والاشتراك ساري.
//
// الملف ده بيحل الأربعة: العرض **صورة**، مش حساب. مفيش كتابة، ومفيش
// صف في أي جدول، والمسوّق مايقدرش يبوّظ حاجة ولا يشوف حاجة مش بتاعته.
//
// والأرقام هنا **معقولة مش مبالغ فيها** عن قصد: كافيه بـ٤٢٠٠ ج
// في اليوم كلام يتصدّق، وكافيه بـ٥٠ ألف بيخلّي صاحب المحل يحس إن
// البرنامج بيتكلم عن محل غير محله.

export type DemoItem = {
  name: string;
  price: number;
  category: string;

  // باركود للأصناف اللي بتتقرا بالماسح. بيظهر تحت الاسم في العرض -
  // صاحب السوبر ماركت بيدوّر عليه بعينه قبل أي حاجة تانية.
  barcode?: string;

  // «له وصفة»: الصنف ده بيخصم مكوّناته لما يتباع.
  recipe?: string;
};

// إزاي المحل ده بيبيع. ده بيغيّر شكل شاشة البيع نفسها، مش كلام
// مكتوب جنبها.
//
//   piece   → بالحبة. زرار + و− بيزوّد واحد.
//   weight  → بالوزن. الخطوة **ربع كيلو** (المصري بيشتري البن
//             والجبنة بالربع)، والكمية بتتكتب ١.٥ مش ٢.
//   service → خدمة. مفيش مخزون أصلًا، والسعر وقت.
export type SellsBy = "piece" | "weight" | "service";

// السطر اللي بيخلّي صاحب المحل يقول "أيوة، دي مشكلتي".
//
// **ده أهم جزء في الملف كله.** المسوّق مش بيبيع برنامج، هو بيبيع
// حل لوجع الراجل اللي قدامه. و**وجع الجزار مش وجع الصيدلي**:
// الجزار بيخاف من الميزان والفرق آخر اليوم، والصيدلي بيخاف من
// الصنف اللي خلص وهو مش واخد باله.
export type DemoPitch = {
  // ٣-٤ حاجات في البرنامج **تخص المجال ده بالذات**.
  features: { title: string; line: string }[];

  // ٢-٣ أوجاع حقيقية بالكلام اللي صاحب المحل بيقوله هو.
  pains: string[];
};

export type DemoShop = {
  businessType: string;
  label: string;
  shopName: string;
  sellsBy: SellsBy;
  categories: string[];
  items: DemoItem[];
  pitch: DemoPitch;

  // سلّة نموذجية للفاتورة المطبوعة.
  basket: { name: string; quantity: number; price: number }[];

  // أرقام آخر اليوم.
  day: {
    sales: number;
    invoices: number;
    expenses: number;
    topItem: string;
  };
};

