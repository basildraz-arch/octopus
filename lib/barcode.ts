// باركود داخلي — توليد ورسم، من غير أي مكتبة
// ============================================================
//
// الملف ده بيعمل حاجتين: بيولّد كود صالح للأصناف اللي المحل
// بيعبّيها بنفسه، وبيرسمه كـSVG جاهز للطباعة.
//
// ============================================================
// ليه اتكتب بالإيد بدل مكتبة جاهزة
// ============================================================
//
// ترميز EAN-13 جداول ثابتة من الثمانينات ومابيتغيّرش. المكتبة
// كانت هتبقى اعتماد زيادة يتسطّب ويتحدّث ويكبّر الحزمة، مقابل
// ٨٠ سطر معروفة. ولأنها خالصة (نفس الدخل = نفس الخرج دايمًا)،
// تقدر تتجرّب من غير متصفح.
//
// ============================================================
// ليه الكود بيبدأ بـ٢
// ============================================================
//
// أرقام EAN-13 اللي بتبدأ بـ **٢** محجوزة عالميًا **للاستعمال
// الداخلي في المحل**. GS1 (الجهة اللي بتوزّع الأرقام) مابتديش
// الرقم ده لأي مصنع، فمستحيل الكود اللي بنولّده يتعارض مع منتج
// حقيقي في السوق.
//
// ده مش تفصيلة. لو ولّدنا رقم عشوائي من غير القاعدة دي، ممكن
// يطلع نفس باركود منتج مشهور — والكاشير يمسح علبة شيبسي فيطلعله
// كيس المكسرات بتاع المحل.
//
// والأرقام دي **مالهاش لازمة بره المحل**: مافيش حد تاني في الدنيا
// هيعرف الكود ده معناه إيه، وde بالظبط المطلوب.

/** خانة التحقق - آخر رقم في الباركود، بتتحسب من الـ١٢ اللي قبلها. */
export function eanCheckDigit(first12: string): number {
  let sum = 0;

  for (let i = 0; i < 12; i++) {
    const digit = Number(first12[i]);

    // الأرقام في المواضع الزوجية (بالعد من واحد) بتتضرب في ٣.
    sum += i % 2 === 0 ? digit : digit * 3;
  }

  return (10 - (sum % 10)) % 10;
}

/**
 * كود داخلي جديد للمحل.
 *
 * بياخد الأكواد المستعملة عنده عشان مايكررش. والقاعدة نفسها فيها
 * فهرس فريد على (المحل، الباركود)، فحتى لو اتنين اتولدوا في نفس
 * اللحظة، التاني بيترفض - الفحص هنا بيمنع الإزعاج، والقاعدة هي
 * الضمان.
 */
export function makeInStoreBarcode(used: Iterable<string>): string {
  const taken = new Set(
    Array.from(used, (code) => (code ?? "").trim())
  );

  // ٥٠ محاولة كتير أوي على ١٠ مليار احتمال. لو خلصوا، فيه حاجة
  // غلط في الدخل مش في الحظ.
  for (let attempt = 0; attempt < 50; attempt++) {
    let body = "2";

    for (let i = 0; i < 11; i++) {
      body += Math.floor(Math.random() * 10);
    }

    const code = body + String(eanCheckDigit(body));

    if (!taken.has(code)) return code;
  }

  throw new Error("تعذر توليد كود جديد. جرّب تاني.");
}

/** الكود صالح كـEAN-13؟ (١٣ رقم وخانة تحقق مظبوطة) */
export function isValidEan13(code: string): boolean {
  const clean = code.trim();

  if (!/^\d{13}$/.test(clean)) return false;

  return eanCheckDigit(clean.slice(0, 12)) === Number(clean[12]);
}

// ============================================================
// الرسم
// ============================================================
//
// كل رقم بيتحوّل لسبع وحدات (أعمدة رفيعة) سودا أو بيضا. الترميز
// بتاع النص الشمال بيختلف حسب أول رقم - وde اللي بيخلي الماسح
// يعرف الباركود مقلوب ولا لأ ويقراه من أي اتجاه.

const L = [
  "0001101", "0011001", "0010011", "0111101", "0100011",
  "0110001", "0101111", "0111011", "0110111", "0001011",
];

const G = [
  "0100111", "0110011", "0011011", "0100001", "0011101",
  "0111001", "0000101", "0010001", "0001001", "0010111",
];

const R = [
  "1110010", "1100110", "1101100", "1000010", "1011100",
  "1001110", "1010000", "1000100", "1001000", "1110100",
];

/** أي جدول يستعمل لكل رقم في النص الشمال، حسب أول رقم. */
const PARITY = [
  "LLLLLL", "LLGLGG", "LLGGLG", "LLGGGL", "LGLLGG",
  "LGGLLG", "LGGGLL", "LGLGLG", "LGLGGL", "LGGLGL",
];

/** ٩٥ وحدة: "1" = عمود أسود، "0" = أبيض. */
export function ean13Modules(code: string): string {
  if (!isValidEan13(code)) {
    throw new Error("الكود ده مش EAN-13 صالح");
  }

  const digits = code.split("").map(Number);
  const parity = PARITY[digits[0]];

  let out = "101"; // حارس البداية

  for (let i = 0; i < 6; i++) {
    const table = parity[i] === "L" ? L : G;
    out += table[digits[i + 1]];
  }

  out += "01010"; // الحارس الأوسط

  for (let i = 0; i < 6; i++) {
    out += R[digits[i + 7]];
  }

  return out + "101"; // حارس النهاية
}

/**
 * الباركود كـSVG.
 *
 * SVG مش صورة عن قصد: الطباعة بتطلع حادة على أي دقة، والصورة
 * النقطية بتتهرّس على الطابعة الحرارية وبتوقف القراءة.
 *
 * `widthMm` عرض الباركود نفسه. الحد الأدنى العملي حوالي ٢٥ مم -
 * أقل من كده الأعمدة بتبقى أرفع من نقطة الطابعة وبتتلحم.
 */
export function ean13Svg(
  code: string,
  widthMm = 32,
  heightMm = 14
): string {
  const modules = ean13Modules(code);
  const unit = widthMm / modules.length;

  // الحرّاس بيطوّلوا تحت السطر عشان العين تفرّق بين الأجزاء -
  // وde شكل الباركود اللي الناس متعوّدة عليه.
  const guards = new Set<number>();
  [0, 1, 2, 45, 46, 47, 48, 49, 92, 93, 94].forEach((i) => guards.add(i));

  let bars = "";

  for (let i = 0; i < modules.length; i++) {
    if (modules[i] !== "1") continue;

    const tall = guards.has(i) ? 1.6 : 0;

    bars +=
      `<rect x="${(i * unit).toFixed(3)}" y="0" ` +
      `width="${unit.toFixed(3)}" height="${(heightMm + tall).toFixed(2)}" ` +
      `fill="#000"/>`;
  }

  const totalHeight = heightMm + 5.2;

  return (
    `<svg xmlns="http://www.w3.org/2000/svg" ` +
    `width="${widthMm}mm" height="${totalHeight}mm" ` +
    `viewBox="0 0 ${widthMm} ${totalHeight}">` +
    bars +
    `<text x="${widthMm / 2}" y="${totalHeight - 0.8}" ` +
    `font-family="monospace" font-size="3.1" text-anchor="middle" ` +
    `fill="#000" letter-spacing="0.35">${code}</text>` +
    `</svg>`
  );
}
