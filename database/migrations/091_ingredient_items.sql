-- ٠٩١ — "مكوّن — مش بيتباع"
--
-- ============================================================
-- المشكلة اللي الوصفات خلقتها
-- ============================================================
--
-- أول ما محل يعمل وصفة لكوباية القهوة، بيضطر يضيف **بن** و**سكر**
-- و**كوب** كأصناف. والتلاتة دول بيظهروا في شاشة الكاشير **جنب
-- القهوة بالظبط**.
--
-- والكاشير بيشتغل بسرعة والزباين واقفة. فدوسة واحدة على "بن" =
-- **بيع كيلو بن** بسعر مالوش أي معنى. المخزون يبقى غلط، والفلوس
-- تبقى غلط، ومحدش يلاحظ.
--
-- ده مش احتمال. ده هيحصل. (باسل هو اللي شاف ده قبل ما يقع فيه.)
--
-- ============================================================
-- ليه علامة مش قاعدة تلقائية
-- ============================================================
--
-- الحل الواضح: "أي صنف بيتستعمل كمكوّن يختفي من شاشة البيع".
-- **وده غلط.**
--
-- محمصة بن بتبيع **كيلو بن** للزبون، **وكمان** بتبيع كوباية قهوة
-- من نفس البن. نفس الصنف، الاستعمالين شرعيين.
--
-- فالبرنامج مايقدرش يقرر. صاحب المحل هو اللي يقول، والبرنامج
-- **يقترح** بس: أول ما صنف يتحط في وصفة، `RecipeEditor` بيسأل
-- "تحب تخفيه من شاشة البيع؟" مرة واحدة.
--
-- الحالة الشايعة بقت دوسة واحدة، والحالة النادرة فضلت ممكنة.
-- (`OCTOPUS_CORE.md`: "Never build for one business only".)
--
-- ============================================================
-- اللي العلامة بتعمله واللي مابتعملهوش
-- ============================================================
--
-- **بتعمل:** الصنف يختفي من شاشة الكاشير (`getActiveItems` بس).
-- شاشة الأصناف والمشتريات والمخزون والتقارير كلهم لسه شايفينه.
--
-- **مابتعملش:** مابتمنعش البيع في القاعدة. لو حد نادى `record_sale`
-- بالصنف ده، هيتباع عادي.
--
-- وde مقصود: العلامة **ترتيب شاشة** مش حاجز أمان. الحاجز الحقيقي
-- للأسعار والصلاحيات في `record_sale` (٠٧٥) وشغّال. لو عملناها
-- حاجز كمان، المحل اللي بيبيع البن **وبيستعمله في وصفة** هيتمنع
-- من بيعه لما يشيل العلامة بالغلط - ومش هيفهم ليه.

alter table public.items
  add column if not exists is_ingredient boolean not null default false;

comment on column public.items.is_ingredient is
  'مكوّن: بيختفي من شاشة الكاشير. ترتيب شاشة مش حاجز أمان (ميجريشن 091).';

-- ============================================================
-- ٠٩١ب — الـgrant. الغلطة اللي وقعت فيها فعلًا
-- ============================================================
--
-- `items` معمولها `revoke select on items` وبعدها
-- `grant select (أعمدة مسمّاة)` عشان `buy_price` يتمنع على مستوى
-- العمود (ميجريشن ٠٧٠).
--
-- ونتيجة كده: **أي عمود جديد بيتضاف للجدول بيبقى ممنوع افتراضيًا**.
-- مابيورثش أي صلاحية.
--
-- فأول استعلام على العمود رجّع:
--
--     ERROR 42501: permission denied for table items
--
-- ولأن شاشة الكاشير بقت بتفلتر بيه، ده كان معناه إن **شاشة البيع
-- كلها تقع** - مش إن العمود مايبانش.
--
-- اتقبض عليها في الاختبار بحساب حقيقي **قبل الرفع**. الغلطة دي
-- مكتوبة في `AGENTS.md` §١ حرفيًا وأنا وقعت فيها برضه - وde بيأكد
-- القاعدة: "نفّذت الأمر" مش دليل، الاستعلام بحساب حقيقي هو الدليل.
--
-- **أي `alter table items add column` لازم يتبعه السطور دي.**

grant select (is_ingredient) on public.items to authenticated;
grant update (is_ingredient) on public.items to authenticated;
grant insert (is_ingredient) on public.items to authenticated;

-- فهرس جزئي: الاستعلام الوحيد اللي بيستعمله هو شاشة البيع، وهي
-- بتسأل عن `is_ingredient = false` بس.
create index if not exists items_sellable
  on public.items (business_id)
  where is_ingredient = false and active;

notify pgrst, 'reload schema';

