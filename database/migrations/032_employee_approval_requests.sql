-- ==========================================
-- OCTOPUS ERP
-- Employee approval requests (Kero item 1 + Basel item 7)
--
-- An Owner submitting "add this cashier" does NOT create a login
-- by itself. It only creates a pending row here. A real `users`
-- row + Supabase Auth account is created ONLY when a platform
-- admin (Master) approves — done server-side (service role) via
-- the Admin Auth API, never through a client-side RLS insert,
-- because RLS alone cannot create an auth.users row.
--
-- generated_email is reserved at request time (unique) so two
-- pending requests for the same business can't collide on the
-- synthetic login email before either is approved.
--
-- No plaintext password is ever stored here. The temporary
-- password is generated by the approval API route at approval
-- time and returned once in the response for the Master to relay
-- to the Owner — it never touches the database.
-- ==========================================

create table if not exists employee_approval_requests (

    id uuid primary key default gen_random_uuid(),

    business_id uuid not null
        references businesses(id)
        on delete cascade,

    requested_by uuid not null
        references users(id)
        on delete cascade,

    full_name text not null,

    phone text,

    branch_id uuid
        references branches(id)
        on delete set null,

    generated_email text not null unique,

    status text not null default 'pending'
        check (status in ('pending', 'approved', 'rejected', 'cancelled')),

    reviewed_by uuid
        references platform_admins(id)
        on delete set null,

    reviewed_at timestamptz,

    rejection_reason text,

    created_user_id uuid
        references users(id)
        on delete set null,

    created_at timestamptz not null default now(),

    updated_at timestamptz not null default now()

);

create index if not exists idx_employee_approval_requests_business
on employee_approval_requests(business_id);

create index if not exists idx_employee_approval_requests_status
on employee_approval_requests(status);

alter table employee_approval_requests enable row level security;

-- Owner can create a request for their own business, as themselves.
drop policy if exists "owner_insert_own_business" on employee_approval_requests;

create policy "owner_insert_own_business" on employee_approval_requests
for insert to authenticated
with check (
  business_id = get_my_business_id()
  and requested_by = (select id from users where auth_user_id = auth.uid())
  and exists (
    select 1 from users
    where users.auth_user_id = auth.uid()
    and users.role = 'owner'
  )
);

-- Owner can see their own business's requests (to track status).
-- Platform admins can see every request across every business.
drop policy if exists "read_requests" on employee_approval_requests;

create policy "read_requests" on employee_approval_requests
for select to authenticated
using (
  business_id = get_my_business_id()
  or is_platform_admin()
);

-- Owner can cancel their OWN still-pending request (nothing else —
-- can't touch status/reviewed_by/created_user_id on anything else).
drop policy if exists "owner_cancel_own_pending" on employee_approval_requests;

create policy "owner_cancel_own_pending" on employee_approval_requests
for update to authenticated
using (
  business_id = get_my_business_id()
  and status = 'pending'
  and requested_by = (select id from users where auth_user_id = auth.uid())
)
with check (
  business_id = get_my_business_id()
  and status = 'cancelled'
  and requested_by = (select id from users where auth_user_id = auth.uid())
);

-- Deliberately NO update policy for platform admins here. Approval
-- is not a plain UPDATE from the client — it must also create a
-- real auth user, which RLS can't do. The approval API route uses
-- the service role key (bypasses RLS entirely, server-side only)
-- after re-checking is_platform_admin() for the caller itself.
