-- 070 - سعر الشرا مبقاش مكشوف للموظفين. **بيتطبّق بعد رفع الكود.**
--
-- آخر حتة من الثغرة الأصلية. ميجريشن 068 قفل الصفوف - المبيعات
-- والمشتريات والمصاريف - لكن التكلفة فضلت مكشوفة في مكانين:
--
--   items.buy_price          متوسط التكلفة لكل صنف
--   stock_batches.buy_price  تكلفة كل دفعة على حدة
--
-- والكاشير لازم يقرا items عشان يبيع، فمنع الصف مش حل. يعني أي كاشير
-- كان يقدر يفتح /rest/v1/items من المتصفح ويطلّع تكلفة كل صنف في
-- المحل - وبالتالي مكسب صاحب المحل في كل حاجة.
--
-- الأبواب البديلة اتفتحت في 069، والكود اللي بيستعملها لازم يكون
-- مرفوع قبل ما ده يتطبّق.

-- ---------------------------------------------------------------- ٤
-- الدفعات: القراءة بقت بصلاحية.
--
-- الكاشير مابقاش محتاجها خالص - السحب بيمر على draw_stock_fifo،
-- والتوفّر بقى على available_quantity.
drop policy if exists stock_batches_read on stock_batches;
create policy stock_batches_read on stock_batches
    for select to authenticated
    using (
        business_id = get_my_business_id()
        and (
            has_read_permission('view_reports')
            or has_read_permission('receive_stock')
            or has_read_permission('manage_items')
        )
    );

-- ---------------------------------------------------------------- ٥
-- والعمود نفسه.
--
-- ده منع على مستوى العمود، يعني بيقع على دور authenticated كله -
-- الأونر كمان. الأونر بياخد التكلفة من item_costs فوق، مش من الجدول
-- مباشرة. ده مقصود: باب واحد بيتحرس، بدل عمود مكشوف وكل استعلام
-- بيحاول يفتكر إنه يستبعده.
revoke select (buy_price) on public.items from authenticated, anon;

-- ---------------------------------------------------------------- لسه ناقص
--
-- draw_stock_fifo لسه بترجّع buy_price لكل دفعة اتسحبت، والكاشير هو
-- اللي بينادي عليها وقت البيعة عشان يكتب sale_items.cost. يعني تكلفة
-- الأصناف اللي بيبيعها بتوصل للمتصفح بتاعه.
--
-- ده أضيق بكتير من قبل كده (صنف وقت بيعه، مش كتالوج المحل كله) بس
-- مش صفر. الحل الصح إن إنشاء الفاتورة كله ينتقل لدالة واحدة في
-- قاعدة البيانات تكتب التكلفة بنفسها، فالمتصفح ما يشوفهاش أصلًا.
-- ده تعديل في مسار البيع نفسه ومحتاج تجربة بيعة حقيقية بعده.
