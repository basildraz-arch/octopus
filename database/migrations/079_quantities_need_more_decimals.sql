-- 079 - أعمدة الكميات بقت بأربع خانات عشرية بدل اتنين.
--
-- ============================================================
-- الغلطة اللي كشفتها الوصفات
-- ============================================================
--
-- كل أعمدة الكميات كانت `numeric(12,2)` - خانتين عشريتين. للقطع
-- والكيلوهات الكاملة ده كفاية. للوصفات هو **كذب**:
--
--   كوباية اسبريسو فيها ١٨ جرام بن = 0.018 كيلو
--   0.018 في عمود بخانتين  →  0.02
--   يعني كل كوباية بتخصم ٢٠ جرام بدل ١٨
--   **زيادة ١١٪ في كل كوباية**
--
-- بعد ألف كوباية: المفروض ينقص ١٨ كيلو، اللي نقص فعلًا ٢٠ كيلو.
-- التقرير بيقول للمالك إن البن خلص وعنده ٢ كيلو على الرف.
--
-- **اتكشفت بالتجربة، مش بالقراءة:** أول اختبار للوصفات باع ٣ كوبايات
-- (المفروض 0.054 كيلو) فنزل المخزون من 2.00 لـ1.95 بدل 1.946.
-- الرقم اللي ظهر هو اللي كشف إن العمود بيقرّب.
--
-- ودي مش مشكلة وصفات بس. جزار بيبيع ١٢٥ جرام لحمة (0.125) كان
-- بيتسجّل 0.13 من قبل الوصفات ما توجد.
--
-- ============================================================
-- الحل ونطاقه
-- ============================================================
--
-- أربع خانات: 0.0001 كيلو = عُشر جرام. كفاية لأي وصفة قهوة أو
-- عطارة أو صيدلية، ومش مبالغة تخلي الأرقام على الشاشة وحشة.
--
-- **أعمدة الكميات بس.** أعمدة الفلوس بتفضل خانتين - الجنيه فيه ١٠٠
-- قرش والخلاص. تكلفة السطر (`sale_items.cost`) بتفضل خانتين لأنها
-- فلوس، والفرق بيتقرّب مرة واحدة في الآخر مش في كل خطوة.
--
-- توسيع الـscale في postgres **عملية آمنة**: مفيش بيانات بتضيع،
-- والقيم الموجودة بتفضل زي ما هي (2.00 بتبقى 2.0000). بس الجدول
-- بيتعاد كتابته، فلو الجداول كبرت أوي بعدين ده هياخد وقت - دلوقتي
-- هي صغيرة.

-- التريجر `trg_notify_low_stock` معرّف بـ`AFTER UPDATE OF stock`،
-- وpostgres بيرفض تغيير نوع عمود مذكور في تعريف تريجر. بنشيله
-- ونرجّعه بنفس التعريف بالظبط.
drop trigger if exists trg_notify_low_stock on public.items;

alter table public.items
    alter column stock         type numeric(14,4),
    alter column minimum_stock type numeric(14,4);

create trigger trg_notify_low_stock
    after update of stock on public.items
    for each row execute function notify_low_stock();

alter table public.stock_batches
    alter column quantity           type numeric(14,4),
    alter column remaining_quantity type numeric(14,4);

alter table public.sale_items
    alter column quantity type numeric(14,4);

alter table public.purchases
    alter column quantity type numeric(14,4);

alter table public.stock_transfers
    alter column quantity type numeric(14,4);

-- `item_components.quantity` معمول `numeric` من غير حدود من الأصل
-- (ميجريشن ٠٧٧) عن قصد - الوصفة هي المكان اللي محتاج أكبر دقة.

notify pgrst, 'reload schema';
